    private void BarraDeBusquedaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BarraDeBusquedaActionPerformed
String textoBusqueda = BarraDeBusqueda.getText().trim().toLowerCase();
    
    if (textoBusqueda.isEmpty()) {
        ShowJPanel(new Principal()); 
        return;
    }
    
    if (textoBusqueda.contains("perro")) {
        if (textoBusqueda.contains("comida") || textoBusqueda.contains("alimento")) {
            ShowJPanel(new ComidaParaPerro());
        } else if (textoBusqueda.contains("accesorio") || textoBusqueda.contains("collar") || textoBusqueda.contains("arnes")) {
            ShowJPanel(new AccesoriosPerro());
        } else if (textoBusqueda.contains("juguete") || textoBusqueda.contains("peluche") || textoBusqueda.contains("juego")) {
            ShowJPanel(new JugetesPerro());
        } else if (textoBusqueda.contains("higiene") || textoBusqueda.contains("shampoo") || textoBusqueda.contains("baño")) {
            ShowJPanel(new HigienePerro());
        } else if (textoBusqueda.contains("habitat") || textoBusqueda.contains("casa") || textoBusqueda.contains("cama")) {
            ShowJPanel(new HabitatPerro());
        } else {
            ShowJPanel(new Perro());
        }
    } 
    else if (textoBusqueda.contains("gato")) {
        if (textoBusqueda.contains("comida") || textoBusqueda.contains("alimento")) {
            ShowJPanel(new ComidaParaGato());
        } else if (textoBusqueda.contains("accesorio") || textoBusqueda.contains("collar") || textoBusqueda.contains("arnes")) {
            ShowJPanel(new AccesoriosGato());
        } else if (textoBusqueda.contains("juguete") || textoBusqueda.contains("ratón") || textoBusqueda.contains("juego")) {
            ShowJPanel(new JugetesGato());
        } else if (textoBusqueda.contains("higiene") || textoBusqueda.contains("shampoo") || textoBusqueda.contains("arena")) {
            ShowJPanel(new HigieneGato());
        } else if (textoBusqueda.contains("hábitat") || textoBusqueda.contains("casa") || textoBusqueda.contains("árbol")) {
            ShowJPanel(new HabitatGato());
        } else {
            ShowJPanel(new Gato());
        }
    }
    else if (textoBusqueda.contains("conejo")) {
        if (textoBusqueda.contains("comida") || textoBusqueda.contains("alimento") || textoBusqueda.contains("heno")) {
            ShowJPanel(new ComidaParaConejo());
        } else if (textoBusqueda.contains("accesorio") || textoBusqueda.contains("correa")) {
            ShowJPanel(new AccesoriosConejo());
        } else if (textoBusqueda.contains("juguete") || textoBusqueda.contains("túnel")) {
            ShowJPanel(new JugetesConejo());
        } else if (textoBusqueda.contains("higiene") || textoBusqueda.contains("shampoo")) {
            ShowJPanel(new HigieneConejo());
        } else if (textoBusqueda.contains("hábitat") || textoBusqueda.contains("casa")) {
            ShowJPanel(new HabitatConejo());
        } else {
            ShowJPanel(new Conejo());
        }
    }
    else if (textoBusqueda.contains("carrito") || textoBusqueda.contains("compra")) {
        ShowJPanel(new Carrito1());
    }
    else if (textoBusqueda.contains("pago") || textoBusqueda.contains("tarjeta") || textoBusqueda.contains("comprar")) {
        ShowJPanel(new Pagos());
    }
    else {
        JOptionPane.showMessageDialog(this, 
            "No se encontraron resultados para: " + textoBusqueda, 
            "Búsqueda sin resultados", 
            JOptionPane.INFORMATION_MESSAGE);
        ShowJPanel(new Principal());
    }
    }//GEN-LAST:event_BarraDeBusquedaActionPerformed

