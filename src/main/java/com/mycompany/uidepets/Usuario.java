     private void addInputValidators() {
       
        NombreIngresa.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();
                if (!(Character.isLetter(c) || c == ' ' || c == KeyEvent.VK_BACK_SPACE || c == KeyEvent.VK_DELETE)) {
                    evt.consume();
                    JOptionPane.showMessageDialog(null, "Solo se permiten letras en el nombre", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        });

        
        ApellidoIngresa.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();
                if (!(Character.isLetter(c) || c == ' ' || c == KeyEvent.VK_BACK_SPACE || c == KeyEvent.VK_DELETE)) {
                    evt.consume();
                    JOptionPane.showMessageDialog(null, "Solo se permiten letras en el apellido", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        });

        
        CedulaIngresa.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();
                if (!(Character.isDigit(c) || c == KeyEvent.VK_BACK_SPACE || c == KeyEvent.VK_DELETE)) {
                    evt.consume();
                    JOptionPane.showMessageDialog(null, "Solo se permiten números en la cédula", "Error", JOptionPane.ERROR_MESSAGE);
                }
                
               
                if (CedulaIngresa.getText().length() >= 10 && c != KeyEvent.VK_BACK_SPACE && c != KeyEvent.VK_DELETE) {
                    evt.consume();
                    JOptionPane.showMessageDialog(null, "La cédula debe tener máximo 10 dígitos", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        });

        
        UbicaccionIngresa.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();
                if (!(Character.isLetterOrDigit(c) || c == ' ' || c == KeyEvent.VK_BACK_SPACE || c == KeyEvent.VK_DELETE)) {
                    evt.consume();
                    JOptionPane.showMessageDialog(null, "No se permiten caracteres especiales en la ubicación", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        });
    }
     

