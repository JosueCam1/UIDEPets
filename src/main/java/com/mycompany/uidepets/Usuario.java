    private void RegistrarseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RegistrarseActionPerformed
        // TODO add your handling code here:
        if (NombreIngresa.getText().isEmpty() || ApellidoIngresa.getText().isEmpty() ||
        CedulaIngresa.getText().isEmpty() || UbicaccionIngresa.getText().isEmpty() ||
        CorreoIngresa.getText().isEmpty() || ContraseñaIngresa.getPassword().length == 0) {
        JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios", 
                "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    
    try {
        int cedula = Integer.parseInt(CedulaIngresa.getText());
        String nombre = NombreIngresa.getText();
        String apellido = ApellidoIngresa.getText();
        String ubicacion = UbicaccionIngresa.getText();
        String correo = CorreoIngresa.getText();
        String contraseña = new String(ContraseñaIngresa.getPassword());
        
       
        if (!correo.matches("^[\\w-\\.]+@([\\w-]+\\.)+[\\w-]{2,4}$")) {
            JOptionPane.showMessageDialog(this, "Formato de correo inválido", 
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try (Connection con = Conexion.establecerConexion()) {
            String sql = "INSERT INTO Usuario (Cedula, Nombre, Apellido, Ubicaccion, Correo, Contraseña) "
                       + "VALUES (?, ?, ?, ?, ?, ?)";
            
            try (PreparedStatement ps = con.prepareStatement(sql)) {
                ps.setInt(1, cedula);
                ps.setString(2, nombre);
                ps.setString(3, apellido);
                ps.setString(4, ubicacion);
                ps.setString(5, correo);
                ps.setString(6, contraseña); 
                
                int filasAfectadas = ps.executeUpdate();
                
                if (filasAfectadas > 0) {
                    JOptionPane.showMessageDialog(this, "Usuario registrado con éxito");
                    Panel Pn = new Panel();
                    Pn.setVisible(true);
                    this.setVisible(false);
                } else {
                    JOptionPane.showMessageDialog(this, "No se pudo registrar el usuario", 
                            "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (SQLException e) {
                if (e.getErrorCode() == 2627) {
                    
                    JOptionPane.showMessageDialog(this, "La cédula ya está registrada", 
                            "Error", JOptionPane.ERROR_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Error al registrar: " + e.getMessage(), 
                            "Error", JOptionPane.ERROR_MESSAGE);
                }
        }
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La cédula debe ser un número válido", 
                "Error", JOptionPane.ERROR_MESSAGE);
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error de conexión o registro: " + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
    }

        

    }//GEN-LAST:event_RegistrarseActionPerformed

